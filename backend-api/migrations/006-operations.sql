--changeset viettrek:v2-006-notification
--comment: Mẫu và bản ghi thông báo. recipient_type ACCOUNT = gửi cho một tài khoản (chuông trong cổng / trang khách); CUSTOMER = khách của một đơn, nhận diện theo SĐT / email đã nhập lúc đặt (có thể không có tài khoản).
CREATE TABLE notification_template (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(64)  NOT NULL,
    channel       varchar(16)  NOT NULL,
    subject       varchar(255),
    body_template text         NOT NULL,
    is_active     boolean      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_notification_template_code UNIQUE (code),
    CONSTRAINT ck_notification_template_channel CHECK (channel IN ('SMS', 'EMAIL', 'ZALO', 'IN_APP', 'PUSH'))
);
ALTER TABLE notification_template ENABLE ROW LEVEL SECURITY;

CREATE TABLE notification (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_code        varchar(64)  NOT NULL REFERENCES notification_template (code),
    channel              varchar(16)  NOT NULL,
    recipient_type       varchar(16)  NOT NULL,
    recipient_account_id bigint REFERENCES account (id) ON DELETE CASCADE,
    recipient_phone      varchar(32),
    recipient_email      varchar(255),
    related_entity_type  varchar(64),
    related_entity_id    bigint,
    payload              jsonb        NOT NULL,
    status               varchar(16)  NOT NULL DEFAULT 'PENDING',
    error_message        varchar(500),
    created_at           timestamp(6) NOT NULL,
    sent_at              timestamp(6),
    CONSTRAINT ck_notification_channel CHECK (channel IN ('SMS', 'EMAIL', 'ZALO', 'IN_APP', 'PUSH')),
    CONSTRAINT ck_notification_recipient_type CHECK (recipient_type IN ('CUSTOMER', 'ACCOUNT')),
    CONSTRAINT ck_notification_recipient CHECK (recipient_type <> 'ACCOUNT' OR recipient_account_id IS NOT NULL),
    CONSTRAINT ck_notification_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);
CREATE INDEX idx_notification_account ON notification (recipient_account_id, created_at);
CREATE INDEX idx_notification_phone ON notification (recipient_phone);
CREATE INDEX idx_notification_email_lower ON notification (lower(recipient_email));
CREATE INDEX idx_notification_template ON notification (template_code);
CREATE INDEX idx_notification_created ON notification (created_at);
ALTER TABLE notification ENABLE ROW LEVEL SECURITY;

