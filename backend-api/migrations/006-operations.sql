--changeset viettrek:v2-006-partner-change-request
--comment: Yêu cầu thay đổi NCC gửi chờ Admin duyệt (thông tin homestay, loại phòng, bảng giá, xuất bản, chuyển NCC). payload / before_data là bản chụp JSON các trường bị đổi.
CREATE TABLE partner_change_request (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id  bigint       NOT NULL REFERENCES provider (id),
    place_id     bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    target_type  varchar(16)  NOT NULL,
    target_id    bigint,
    room_type_id bigint REFERENCES room_type (id) ON DELETE SET NULL,
    operation    varchar(8)   NOT NULL,
    status       varchar(16)  NOT NULL DEFAULT 'PENDING',
    payload      jsonb,
    before_data  jsonb,
    submitted_by bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    submitted_at timestamp(6) NOT NULL,
    reviewed_by  bigint REFERENCES account (id) ON DELETE SET NULL,
    reviewed_at  timestamp(6),
    review_note  varchar(500),
    CONSTRAINT ck_partner_change_request_target CHECK (target_type IN ('HOMESTAY', 'ROOM_TYPE', 'ROOM_PRICE')),
    CONSTRAINT ck_partner_change_request_operation CHECK (operation IN ('CREATE', 'UPDATE', 'DELETE', 'PUBLISH', 'TRANSFER')),
    CONSTRAINT ck_partner_change_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED'))
);
CREATE INDEX idx_partner_change_request_status ON partner_change_request (status, submitted_at);
CREATE INDEX idx_partner_change_request_provider ON partner_change_request (provider_id, status);
CREATE INDEX idx_partner_change_request_place ON partner_change_request (place_id, status);
CREATE INDEX idx_partner_change_request_room_type ON partner_change_request (room_type_id);
CREATE INDEX idx_partner_change_request_submitted_by ON partner_change_request (submitted_by);
CREATE INDEX idx_partner_change_request_reviewed_by ON partner_change_request (reviewed_by);
ALTER TABLE partner_change_request ENABLE ROW LEVEL SECURITY;
