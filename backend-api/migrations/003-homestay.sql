--changeset viettrek:v2-003-cancellation-policy
--comment: Chính sách hủy của homestay, có phiên bản; đơn đặt lưu snapshot chính sách lúc đặt (booking.policy_snapshot).
CREATE TABLE cancellation_policy (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id                 bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    version                  integer      NOT NULL,
    name                     varchar(255) NOT NULL,
    free_cancel_cutoff_hours integer      NOT NULL,
    refund_on_late_cancel    varchar(16)  NOT NULL DEFAULT 'NO_REFUND',
    content_text             text         NOT NULL,
    effective_from           timestamp(6) NOT NULL,
    created_by               bigint REFERENCES account (id) ON DELETE SET NULL,
    CONSTRAINT uq_cancellation_policy_version UNIQUE (place_id, version),
    CONSTRAINT ck_cancellation_policy_cutoff CHECK (free_cancel_cutoff_hours >= 0),
    CONSTRAINT ck_cancellation_policy_refund CHECK (refund_on_late_cancel IN ('FULL_REFUND', 'NO_REFUND'))
);
CREATE INDEX idx_cancellation_policy_created_by ON cancellation_policy (created_by);
ALTER TABLE cancellation_policy ENABLE ROW LEVEL SECURITY;

