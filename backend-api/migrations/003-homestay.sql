--changeset viettrek:v2-003-room-inventory
--comment: Tồn phòng theo ngày — NGUỒN SỰ THẬT của số phòng bán được: total_rooms (đang mở bán), held_rooms (đơn chờ xác nhận giữ), confirmed_rooms (đơn đã xác nhận / đã thanh toán). Không có dòng = còn nguyên total_room_count của loại phòng. room_unit_day chỉ nhớ VỊ TRÍ từng phòng trên lịch theo phòng (Phòng 1, Phòng 2...) để ô chủ nhà bấm khóa đúng là ô đổi màu; số lượng vẫn lấy từ room_inventory_day.
CREATE TABLE room_inventory_day (
    room_type_id    bigint       NOT NULL REFERENCES room_type (id) ON DELETE CASCADE,
    stay_date       date         NOT NULL,
    total_rooms     integer      NOT NULL,
    held_rooms      integer      NOT NULL DEFAULT 0,
    confirmed_rooms integer      NOT NULL DEFAULT 0,
    stop_sell       boolean      NOT NULL DEFAULT FALSE,
    block_reason    varchar(255),
    available_rooms integer GENERATED ALWAYS AS (
        CASE WHEN stop_sell THEN 0 ELSE GREATEST(total_rooms - held_rooms - confirmed_rooms, 0) END) STORED,
    updated_at      timestamp(6) NOT NULL,
    PRIMARY KEY (room_type_id, stay_date),
    CONSTRAINT ck_room_inventory_counts CHECK (total_rooms >= 0 AND held_rooms >= 0 AND confirmed_rooms >= 0)
);
ALTER TABLE room_inventory_day ENABLE ROW LEVEL SECURITY;

CREATE TABLE room_unit_day (
    room_type_id bigint     NOT NULL REFERENCES room_type (id) ON DELETE CASCADE,
    stay_date    date       NOT NULL,
    unit_no      integer    NOT NULL,
    state        varchar(8) NOT NULL,
    PRIMARY KEY (room_type_id, stay_date, unit_no),
    CONSTRAINT ck_room_unit_day_unit CHECK (unit_no >= 1),
    CONSTRAINT ck_room_unit_day_state CHECK (state IN ('GUEST', 'LOCKED'))
);
ALTER TABLE room_unit_day ENABLE ROW LEVEL SECURITY;
