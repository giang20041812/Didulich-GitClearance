--changeset viettrek:v2-005-journey
--comment: Lịch trình của khách (miễn phí, tách khỏi đơn đặt phòng) và các điểm đến theo ngày + buổi. Xóa tài khoản thì xóa lịch trình; xóa đơn thì chỉ bỏ gắn. share_token: trang chia sẻ /j/{token}; published_at: đăng lên trang "Trải nghiệm".
CREATE TABLE journey (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    traveler_id        bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    base_place_id      bigint REFERENCES place (id) ON DELETE SET NULL,
    booking_id         bigint REFERENCES booking (id) ON DELETE SET NULL,
    title              varchar(160),
    start_date         date,
    end_date           date,
    share_token        varchar(32),
    published_at       timestamp(6),
    feed_hidden_at     timestamp(6),
    feed_hidden_reason varchar(500),
    created_at         timestamp(6) NOT NULL,
    updated_at         timestamp(6) NOT NULL,
    CONSTRAINT uq_journey_booking UNIQUE (booking_id),
    CONSTRAINT uq_journey_share_token UNIQUE (share_token),
    CONSTRAINT ck_journey_dates CHECK (start_date IS NULL OR end_date IS NULL OR start_date <= end_date)
);
CREATE INDEX idx_journey_traveler ON journey (traveler_id, updated_at);
CREATE INDEX idx_journey_base_place ON journey (base_place_id);
CREATE INDEX idx_journey_published ON journey (published_at) WHERE published_at IS NOT NULL;
ALTER TABLE journey ENABLE ROW LEVEL SECURITY;

CREATE TABLE journey_stop (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_id       bigint      NOT NULL REFERENCES journey (id) ON DELETE CASCADE,
    place_id         bigint      NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    visit_date       date,
    day_session      varchar(16) NOT NULL,
    sort_order       integer     NOT NULL DEFAULT 0,
    reminder_sent_at timestamp(6),
    CONSTRAINT ck_journey_stop_day_session CHECK (day_session IN ('MORNING', 'NOON', 'AFTERNOON', 'EVENING'))
);
CREATE INDEX idx_journey_stop_journey ON journey_stop (journey_id);
CREATE INDEX idx_journey_stop_place ON journey_stop (place_id);
-- Job nhắc giờ tham quan chỉ quét điểm chưa nhắc.
CREATE INDEX idx_journey_stop_reminder_due ON journey_stop (visit_date) WHERE reminder_sent_at IS NULL;
ALTER TABLE journey_stop ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-005-journey-checkin
--comment: Check-in địa điểm của khách (ảnh + lưu bút), Admin ẩn được; mỗi lịch trình check-in một địa điểm tối đa một lần. Lượt "hữu ích" của khách cho lịch trình đã đăng.
CREATE TABLE journey_checkin (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    traveler_id          bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    journey_id           bigint REFERENCES journey (id) ON DELETE SET NULL,
    place_id             bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    photo_url            varchar(1000),
    note                 varchar(1000),
    hidden_at            timestamp(6),
    hidden_reason        varchar(500),
    hidden_by_account_id bigint REFERENCES account (id) ON DELETE SET NULL,
    created_at           timestamp(6) NOT NULL,
    updated_at           timestamp(6) NOT NULL,
    CONSTRAINT uq_journey_checkin_place UNIQUE (journey_id, place_id)
);
CREATE INDEX idx_journey_checkin_traveler ON journey_checkin (traveler_id, created_at);
CREATE INDEX idx_journey_checkin_place ON journey_checkin (place_id);
CREATE INDEX idx_journey_checkin_created ON journey_checkin (created_at);
CREATE INDEX idx_journey_checkin_hidden_by ON journey_checkin (hidden_by_account_id);
ALTER TABLE journey_checkin ENABLE ROW LEVEL SECURITY;

CREATE TABLE journey_helpful (
    journey_id  bigint       NOT NULL REFERENCES journey (id) ON DELETE CASCADE,
    traveler_id bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    created_at  timestamp(6) NOT NULL,
    PRIMARY KEY (journey_id, traveler_id)
);
CREATE INDEX idx_journey_helpful_traveler ON journey_helpful (traveler_id);
ALTER TABLE journey_helpful ENABLE ROW LEVEL SECURITY;
