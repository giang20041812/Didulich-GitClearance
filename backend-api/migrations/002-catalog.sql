--comment: Thông tin riêng của điểm tham quan (place.kind = ATTRACTION). needs: enjoy (tận hưởng) / adventure (khám phá). suitable_sessions: buổi phù hợp, mã cách nhau bằng dấu phẩy. Mùa đẹp lặp lại hằng năm, lưu dạng MMDD (915 = 15/9; mùa qua năm mới thì start > end). visit_minutes: thời gian tham quan gợi ý.
