--changeset viettrek:v2-008-trip-addon
--comment: Dịch vụ thêm gắn vào lịch trình (xe Hà Nội – MCC, HDV bản địa, flycam, dù lượn, đặt món). Không có cột giá — theo gói gốc ("giá ưu đãi riêng"), khách liên hệ tư vấn. note = ghi chú ngắn hiện cạnh tên (vd "Đã gồm trong combo").
CREATE TABLE trip_addon (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(32)  NOT NULL,
    name        varchar(160) NOT NULL,
    description varchar(500),
    note        varchar(255),
    is_active   boolean      NOT NULL DEFAULT TRUE,
    sort_order  integer      NOT NULL DEFAULT 0,
    CONSTRAINT uq_trip_addon_code UNIQUE (code),
    CONSTRAINT ck_trip_addon_code CHECK (code ~ '^[A-Z][A-Z0-9_]*$')
);
ALTER TABLE trip_addon ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-008-trip-template
--comment: Lịch trình mẫu (gói) của từng tỉnh — nguồn gợi ý của trang /lich-trinh. Khách lọc gói theo tag: thời lượng (days/nights), mốc giá mỗi người (price_from), tag ăn uống / mục tiêu (bảng tag, group_code TRIP_DINING / TRIP_GOAL, nối qua trip_template_tag). content (jsonb): các mục theo ngày + giờ — cấu trúc ở docs/lich-trinh-goi-y.md mục 5.
CREATE TABLE trip_template (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(64)    NOT NULL,
    region_id  bigint         NOT NULL REFERENCES region (id) ON DELETE CASCADE,
    title      varchar(160)   NOT NULL,
    summary    varchar(500),
    days       smallint       NOT NULL,
    nights     smallint       NOT NULL,
    price_from numeric(14, 2),
    content    jsonb          NOT NULL,
    visibility varchar(16)    NOT NULL DEFAULT 'DRAFT',
    sort_order integer        NOT NULL DEFAULT 0,
    created_at timestamp(6)   NOT NULL,
    updated_at timestamp(6)   NOT NULL,
    CONSTRAINT uq_trip_template_code UNIQUE (code),
    CONSTRAINT ck_trip_template_days CHECK (days BETWEEN 1 AND 14 AND nights BETWEEN 0 AND days),
    CONSTRAINT ck_trip_template_price CHECK (price_from IS NULL OR price_from >= 0),
    CONSTRAINT ck_trip_template_visibility CHECK (visibility IN ('DRAFT', 'PUBLISHED', 'UNPUBLISHED'))
);
CREATE INDEX idx_trip_template_region ON trip_template (region_id);
ALTER TABLE trip_template ENABLE ROW LEVEL SECURITY;

CREATE TABLE trip_template_tag (
    template_id bigint NOT NULL REFERENCES trip_template (id) ON DELETE CASCADE,
    tag_id      bigint NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    PRIMARY KEY (template_id, tag_id)
);
CREATE INDEX idx_trip_template_tag_tag ON trip_template_tag (tag_id);
ALTER TABLE trip_template_tag ENABLE ROW LEVEL SECURITY;

