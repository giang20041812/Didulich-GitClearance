CREATE INDEX idx_journey_region ON journey (region_id);

--changeset viettrek:v2-008-journey-stop-items
--comment: Mục lịch trình nhiều loại: PLACE (điểm tham quan — như cũ), MEAL, ACTIVITY, TRANSPORT, STAY (ô chỗ ở), FREE. Mục không có địa điểm dùng title + note. day_index = Ngày N (lịch trình chưa có ngày đi vẫn xếp được theo ngày). start_time / end_time = giờ của mục. addons = mã trip_addon cách nhau dấu phẩy.
ALTER TABLE journey_stop
    ALTER COLUMN place_id DROP NOT NULL,
    ADD COLUMN kind       varchar(16) NOT NULL DEFAULT 'PLACE',
    ADD COLUMN title      varchar(160),
    ADD COLUMN day_index  smallint,
    ADD COLUMN start_time time(6),
    ADD COLUMN end_time   time(6),
    ADD COLUMN note       varchar(1000),
    ADD COLUMN addons     varchar(255),
    ADD CONSTRAINT ck_journey_stop_kind CHECK (kind IN ('PLACE', 'MEAL', 'ACTIVITY', 'TRANSPORT', 'STAY', 'FREE')),
    ADD CONSTRAINT ck_journey_stop_place CHECK (kind <> 'PLACE' OR place_id IS NOT NULL),
    ADD CONSTRAINT ck_journey_stop_label CHECK (place_id IS NOT NULL OR title IS NOT NULL),
    ADD CONSTRAINT ck_journey_stop_day_index CHECK (day_index IS NULL OR day_index BETWEEN 1 AND 61),
    ADD CONSTRAINT ck_journey_stop_time CHECK (start_time IS NULL OR end_time IS NULL OR start_time <= end_time),
    ADD CONSTRAINT ck_journey_stop_addons CHECK (addons IS NULL OR addons ~ '^[A-Z][A-Z0-9_]*(,[A-Z][A-Z0-9_]*)*$');

