CREATE TABLE combo (
    id                    bigint         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                  varchar(180)   NOT NULL UNIQUE,
    title                 varchar(150)   NOT NULL,
    summary               varchar(300)   NOT NULL,
    description           text,
    days                  integer        NOT NULL,
    nights                integer        NOT NULL,
    price_from            numeric(14, 2) NOT NULL,
    price_note            varchar(255),
    group_size_min        integer,
    group_size_max        integer,
    includes              varchar(2000),
    excludes              varchar(2000),
    cover_image_url       varchar(1000),
    provider_id           bigint         REFERENCES provider (id) ON DELETE CASCADE,
    status                varchar(16)    NOT NULL,
    visible               boolean        NOT NULL DEFAULT TRUE,
    paused                boolean        NOT NULL DEFAULT FALSE,
    reject_reason         varchar(500),
    pending_payload       json,
    pending_submitted_at  timestamp(6),
    pending_reject_reason varchar(500),
    submitted_at          timestamp(6),
    reviewed_at           timestamp(6),
    reviewed_by           bigint         REFERENCES account (id) ON DELETE SET NULL,
    created_by            bigint         REFERENCES account (id) ON DELETE SET NULL,
    updated_by            bigint         REFERENCES account (id) ON DELETE SET NULL,
    created_at            timestamp(6)   NOT NULL,
    updated_at            timestamp(6)   NOT NULL,
    CONSTRAINT ck_combo_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_combo_rejected CHECK (status <> 'REJECTED' OR reject_reason IS NOT NULL),
    CONSTRAINT ck_combo_days CHECK (days BETWEEN 1 AND 15),
    CONSTRAINT ck_combo_nights CHECK (nights BETWEEN 0 AND 15 AND nights <= days),
    CONSTRAINT ck_combo_price CHECK (price_from >= 0),
    CONSTRAINT ck_combo_group_size CHECK ((group_size_min IS NULL OR group_size_min BETWEEN 1 AND 100)
        AND (group_size_max IS NULL OR group_size_max BETWEEN 1 AND 100)
        AND (group_size_min IS NULL OR group_size_max IS NULL OR group_size_min <= group_size_max))
);
CREATE INDEX idx_combo_provider ON combo (provider_id);
CREATE INDEX idx_combo_status ON combo (status, visible, paused);
CREATE INDEX idx_combo_reviewed_by ON combo (reviewed_by);
CREATE INDEX idx_combo_created_by ON combo (created_by);
CREATE INDEX idx_combo_updated_by ON combo (updated_by);
ALTER TABLE combo ENABLE ROW LEVEL SECURITY;

CREATE TABLE combo_stop (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_id   bigint       NOT NULL REFERENCES combo (id) ON DELETE CASCADE,
    day_no     integer      NOT NULL,
    sort_order integer      NOT NULL,
    start_time time,
    end_time   time,
    place_id   bigint       REFERENCES place (id) ON DELETE SET NULL,
    title      varchar(150) NOT NULL,
    note       varchar(1000),
    CONSTRAINT ck_combo_stop_day CHECK (day_no BETWEEN 1 AND 15),
    CONSTRAINT uq_combo_stop_order UNIQUE (combo_id, day_no, sort_order)
);
CREATE INDEX idx_combo_stop_place ON combo_stop (place_id);
ALTER TABLE combo_stop ENABLE ROW LEVEL SECURITY;

CREATE TABLE combo_restaurant (
    combo_id   bigint       NOT NULL REFERENCES combo (id) ON DELETE CASCADE,
    place_id   bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    sort_order integer      NOT NULL,
    note       varchar(255),
    PRIMARY KEY (combo_id, place_id)
);
CREATE INDEX idx_combo_restaurant_place ON combo_restaurant (place_id);
ALTER TABLE combo_restaurant ENABLE ROW LEVEL SECURITY;

CREATE TABLE combo_request (
    id                  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_id            bigint       NOT NULL REFERENCES combo (id) ON DELETE CASCADE,
    traveler_account_id bigint       REFERENCES account (id) ON DELETE SET NULL,
    contact_name        varchar(120) NOT NULL,
    contact_phone       varchar(20)  NOT NULL,
    start_date          date         NOT NULL,
    guests              integer      NOT NULL,
    note                varchar(1000),
    status              varchar(16)  NOT NULL DEFAULT 'NEW',
    handled_by          bigint       REFERENCES account (id) ON DELETE SET NULL,
    handled_at          timestamp(6),
    created_at          timestamp(6) NOT NULL,
    CONSTRAINT ck_combo_request_status CHECK (status IN ('NEW', 'CONTACTED', 'CLOSED')),
    CONSTRAINT ck_combo_request_guests CHECK (guests BETWEEN 1 AND 100)
);
CREATE INDEX idx_combo_request_combo ON combo_request (combo_id, status);
CREATE INDEX idx_combo_request_traveler ON combo_request (traveler_account_id);
CREATE INDEX idx_combo_request_handled_by ON combo_request (handled_by);
ALTER TABLE combo_request ENABLE ROW LEVEL SECURITY;

