--changeset viettrek:v2-001-provider
--comment: Nhà cung cấp (đơn vị kinh doanh sở hữu homestay). Không xóa cứng — khóa bằng status.
CREATE TABLE provider (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(255) NOT NULL,
    contact_name  varchar(255),
    contact_phone varchar(32),
    contact_email varchar(255),
    address       varchar(500),
    note          text,
    status        varchar(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    timestamp(6) NOT NULL,
    updated_at    timestamp(6) NOT NULL,
    CONSTRAINT ck_provider_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'TERMINATED'))
);
ALTER TABLE provider ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-001-account
--comment: Tài khoản DUY NHẤT cho mọi người dùng (gộp account + traveler cũ). role là cổng cao nhất được vào: ADMIN, PROVIDER hoặc TRAVELER; mọi tài khoản đang hoạt động đều dùng được trang khách bằng chính tài khoản đó. Email lưu chữ thường, duy nhất không phân biệt hoa/thường. password_hash NULL chỉ với khách đăng nhập Google.
CREATE TABLE account (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             varchar(255),
    phone             varchar(32),
    password_hash     varchar(255),
    full_name         varchar(255),
    avatar_url        varchar(1000),
    role              varchar(16)  NOT NULL,
    status            varchar(16)  NOT NULL DEFAULT 'ACTIVE',
    admin_level       integer,
    provider_id       bigint REFERENCES provider (id),
    email_verified_at timestamp(6),
    token_version     integer      NOT NULL DEFAULT 0,
    last_login_at     timestamp(6),
    last_activity_at  timestamp(6),
    created_at        timestamp(6) NOT NULL,
    CONSTRAINT uq_account_phone UNIQUE (phone),
    CONSTRAINT ck_account_identifier CHECK (email IS NOT NULL OR phone IS NOT NULL),
    CONSTRAINT ck_account_role CHECK (role IN ('ADMIN', 'PROVIDER', 'TRAVELER')),
    CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_account_admin_level CHECK (admin_level IS NULL OR (role = 'ADMIN' AND admin_level BETWEEN 1 AND 3)),
    CONSTRAINT ck_account_password CHECK (password_hash IS NOT NULL OR role = 'TRAVELER')
);
CREATE UNIQUE INDEX uq_account_email ON account (lower(email));
CREATE INDEX idx_account_provider ON account (provider_id);
CREATE INDEX idx_account_role_status ON account (role, status);
ALTER TABLE account ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-001-account-session
--comment: Phiên đăng nhập theo thiết bị của cổng Admin / NCC (JWT mang claim "sid"). Đăng xuất xóa đúng dòng của thiết bị.
CREATE TABLE account_session (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    session_key   char(32)     NOT NULL,
    token_version integer      NOT NULL,
    created_at    timestamp(6) NOT NULL,
    CONSTRAINT uq_account_session_key UNIQUE (session_key)
);
CREATE INDEX idx_account_session_account ON account_session (account_id);
ALTER TABLE account_session ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-001-password-reset-token
--comment: Mã OTP đặt lại mật khẩu (chỉ lưu bản băm) — của mọi loại tài khoản.
CREATE TABLE password_reset_token (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    email      varchar(255) NOT NULL,
    otp_hash   varchar(100) NOT NULL,
    expires_at timestamp(6) NOT NULL,
    attempts   integer      NOT NULL DEFAULT 0,
    used_at    timestamp(6),
    created_at timestamp(6) NOT NULL
);
CREATE INDEX idx_password_reset_account ON password_reset_token (account_id, created_at);
ALTER TABLE password_reset_token ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-001-push-subscription
--comment: Thông báo đẩy (Web Push): mỗi trình duyệt / thiết bị bật thông báo là một dòng. scope PORTAL = cổng Admin / NCC, TRAVELER = trang khách (nhắc giờ tham quan); cùng một trình duyệt có thể đăng ký cả hai.
CREATE TABLE push_subscription (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    bigint       NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    scope         varchar(16)  NOT NULL,
    endpoint_hash char(64)     NOT NULL,
    endpoint      text         NOT NULL,
    p256dh        varchar(255) NOT NULL,
    auth          varchar(255) NOT NULL,
    user_agent    varchar(255),
    created_at    timestamp(6) NOT NULL,
    CONSTRAINT uq_push_subscription_endpoint UNIQUE (scope, endpoint_hash),
    CONSTRAINT ck_push_subscription_scope CHECK (scope IN ('PORTAL', 'TRAVELER'))
);
CREATE INDEX idx_push_subscription_account ON push_subscription (account_id, scope);
ALTER TABLE push_subscription ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-001-provider-application
--comment: Hồ sơ đăng ký làm NCC. Mật khẩu (bản băm) người nộp đặt được chép sang tài khoản khi duyệt.
CREATE TABLE provider_application (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name       varchar(255) NOT NULL,
    contact_name        varchar(255) NOT NULL,
    contact_phone       varchar(32)  NOT NULL,
    contact_email       varchar(255),
    address             varchar(500) NOT NULL,
    business_license_no varchar(64),
    description         text,
    password_hash       varchar(255) NOT NULL,
    status              varchar(16)  NOT NULL DEFAULT 'PENDING',
    review_note         varchar(500),
    reviewed_by         bigint REFERENCES account (id) ON DELETE SET NULL,
    reviewed_at         timestamp(6),
    provider_id         bigint REFERENCES provider (id) ON DELETE SET NULL,
    created_at          timestamp(6) NOT NULL,
    CONSTRAINT ck_provider_application_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED'))
);
CREATE INDEX idx_provider_application_status ON provider_application (status, created_at);
CREATE INDEX idx_provider_application_phone ON provider_application (contact_phone);
CREATE INDEX idx_provider_application_reviewed_by ON provider_application (reviewed_by);
CREATE INDEX idx_provider_application_provider ON provider_application (provider_id);
ALTER TABLE provider_application ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-001-affiliate-link
--comment: Link giới thiệu (affiliate) của một tài khoản.
CREATE TABLE affiliate_link (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      bigint        NOT NULL REFERENCES account (id) ON DELETE CASCADE,
    code            varchar(64)   NOT NULL,
    commission_rate numeric(5, 4) NOT NULL,
    is_active       boolean       NOT NULL DEFAULT TRUE,
    created_at      timestamp(6)  NOT NULL,
    CONSTRAINT uq_affiliate_link_code UNIQUE (code),
    CONSTRAINT ck_affiliate_link_rate CHECK (commission_rate >= 0 AND commission_rate <= 1)
);
CREATE INDEX idx_affiliate_link_account ON affiliate_link (account_id);
ALTER TABLE affiliate_link ENABLE ROW LEVEL SECURITY;
