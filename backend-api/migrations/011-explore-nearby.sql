CREATE TABLE homestay_explore_pin (
    homestay_id bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    place_id    bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    sort_order  integer      NOT NULL,
    created_by  bigint REFERENCES account (id) ON DELETE SET NULL,
    created_at  timestamp(6) NOT NULL,
    PRIMARY KEY (homestay_id, place_id),
    CONSTRAINT ck_homestay_explore_pin_self CHECK (homestay_id <> place_id)
);
CREATE INDEX idx_homestay_explore_pin_place ON homestay_explore_pin (place_id);
CREATE INDEX idx_homestay_explore_pin_created_by ON homestay_explore_pin (created_by);
ALTER TABLE homestay_explore_pin ENABLE ROW LEVEL SECURITY;

CREATE TABLE place_edit_request (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id      bigint       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    payload       json         NOT NULL,
    status        varchar(16)  NOT NULL,
    reject_reason varchar(500),
    submitted_by  bigint REFERENCES account (id) ON DELETE SET NULL,
    submitted_at  timestamp(6) NOT NULL,
    reviewed_by   bigint REFERENCES account (id) ON DELETE SET NULL,
    reviewed_at   timestamp(6),
    CONSTRAINT ck_place_edit_request_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_place_edit_request_rejected CHECK (status <> 'REJECTED' OR reject_reason IS NOT NULL)
);
CREATE UNIQUE INDEX uq_place_edit_request_pending ON place_edit_request (place_id) WHERE status = 'PENDING';
CREATE INDEX idx_place_edit_request_place ON place_edit_request (place_id, status);
CREATE INDEX idx_place_edit_request_submitted_by ON place_edit_request (submitted_by);
CREATE INDEX idx_place_edit_request_reviewed_by ON place_edit_request (reviewed_by);
ALTER TABLE place_edit_request ENABLE ROW LEVEL SECURITY;

