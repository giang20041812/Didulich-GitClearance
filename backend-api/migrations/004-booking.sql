--changeset viettrek:v2-004-booking
--comment: Đơn đặt phòng. Một đơn ở MỘT homestay, cùng ngày nhận / trả phòng, gồm MỘT HOẶC NHIỀU loại phòng (booking_room) với giá từng đêm (booking_night). provider_id là NCC sở hữu homestay LÚC ĐẶT (giữ cho đối soát kể cả khi homestay đổi chủ). Thông tin khách (guest_*) là bản chụp lúc đặt; traveler_id = tài khoản đặt đơn (NULL khi đặt không đăng nhập). Nhận / trả phòng là mốc thời gian, không phải trạng thái.
CREATE TABLE booking (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code      varchar(32)    NOT NULL,
    place_id          bigint         NOT NULL REFERENCES place (id),
    provider_id       bigint         NOT NULL REFERENCES provider (id),
    traveler_id       bigint REFERENCES account (id) ON DELETE SET NULL,
    check_in          date           NOT NULL,
    check_out         date           NOT NULL,
    nights            integer GENERATED ALWAYS AS (check_out - check_in) STORED,
    guest_count       integer        NOT NULL,
    guest_name        varchar(255)   NOT NULL,
    guest_phone       varchar(32)    NOT NULL,
    guest_email       varchar(255),
    guest_note        text,
    status            varchar(16)    NOT NULL DEFAULT 'PENDING',
    currency          char(3)        NOT NULL DEFAULT 'VND',
    total_amount      numeric(14, 2) NOT NULL,
    policy_id         bigint REFERENCES cancellation_policy (id),
    policy_snapshot   jsonb          NOT NULL,
    access_token_hash varchar(64),
    created_at        timestamp(6)   NOT NULL,
    confirmed_at      timestamp(6),
    closed_at         timestamp(6),
    close_reason      varchar(500),
    closed_by_actor   varchar(16),
    checked_in_at     timestamp(6),
    checked_in_by     varchar(16),
    checked_out_at    timestamp(6),
    checked_out_by    varchar(16),
    CONSTRAINT uq_booking_code UNIQUE (booking_code),
    CONSTRAINT ck_booking_dates CHECK (check_out > check_in),
    CONSTRAINT ck_booking_guest_count CHECK (guest_count > 0),
    CONSTRAINT ck_booking_total CHECK (total_amount >= 0),
    CONSTRAINT ck_booking_status CHECK (status IN ('PENDING', 'CONFIRMED', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_booking_actors CHECK (
        (closed_by_actor IS NULL OR closed_by_actor IN ('CUSTOMER', 'PROVIDER', 'ADMIN', 'SYSTEM'))
        AND (checked_in_by IS NULL OR checked_in_by IN ('CUSTOMER', 'PROVIDER', 'ADMIN', 'SYSTEM'))
        AND (checked_out_by IS NULL OR checked_out_by IN ('CUSTOMER', 'PROVIDER', 'ADMIN', 'SYSTEM'))),
    CONSTRAINT ck_booking_stay CHECK ((checked_in_at IS NULL) = (checked_in_by IS NULL)
        AND (checked_out_at IS NULL) = (checked_out_by IS NULL)
        AND (checked_out_at IS NULL OR checked_in_at IS NOT NULL))
);
-- Chống trùng đơn còn hiệu lực (bấm "Đặt phòng" hai lần / mạng gửi lại): cùng homestay + SĐT + ngày.
CREATE UNIQUE INDEX uq_booking_active_dup ON booking (place_id, guest_phone, check_in, check_out) WHERE status IN ('PENDING', 'CONFIRMED');
CREATE INDEX idx_booking_place_dates ON booking (place_id, check_in);
CREATE INDEX idx_booking_provider_created ON booking (provider_id, created_at);
CREATE INDEX idx_booking_traveler ON booking (traveler_id);
CREATE INDEX idx_booking_status_created ON booking (status, created_at);
CREATE INDEX idx_booking_created ON booking (created_at);
CREATE INDEX idx_booking_policy ON booking (policy_id);
CREATE INDEX idx_booking_guest_phone ON booking (guest_phone);
CREATE INDEX idx_booking_guest_email_lower ON booking (lower(guest_email));
-- Job tự trả phòng chỉ quét đơn đang ở.
CREATE INDEX idx_booking_in_house ON booking (check_out) WHERE checked_in_at IS NOT NULL AND checked_out_at IS NULL;
ALTER TABLE booking ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-004-booking-room
--comment: Các loại phòng trong một đơn (số phòng mỗi loại) và giá từng đêm của mỗi loại. Tổng tiền đơn = tổng unit_price × room_count qua mọi đêm, mọi loại phòng.
CREATE TABLE booking_room (
    booking_id   bigint  NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    room_type_id bigint  NOT NULL REFERENCES room_type (id),
    room_count   integer NOT NULL,
    PRIMARY KEY (booking_id, room_type_id),
    CONSTRAINT ck_booking_room_count CHECK (room_count > 0)
);
CREATE INDEX idx_booking_room_room_type ON booking_room (room_type_id);
ALTER TABLE booking_room ENABLE ROW LEVEL SECURITY;

CREATE TABLE booking_night (
    booking_id   bigint         NOT NULL,
    room_type_id bigint         NOT NULL,
    stay_date    date           NOT NULL,
    unit_price   numeric(14, 2) NOT NULL,
    PRIMARY KEY (booking_id, room_type_id, stay_date),
    CONSTRAINT fk_booking_night_room FOREIGN KEY (booking_id, room_type_id)
        REFERENCES booking_room (booking_id, room_type_id) ON DELETE CASCADE,
    CONSTRAINT ck_booking_night_price CHECK (unit_price >= 0)
);
ALTER TABLE booking_night ENABLE ROW LEVEL SECURITY;

--changeset viettrek:v2-004-booking-history
--comment: Lịch sử trạng thái đơn và ghi chú giám sát của Admin.
CREATE TABLE booking_status_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  bigint       NOT NULL REFERENCES booking (id) ON DELETE CASCADE,
    from_status varchar(16),
    to_status   varchar(16)  NOT NULL,
    actor       varchar(16)  NOT NULL,
    actor_id    bigint REFERENCES account (id) ON DELETE SET NULL,
    reason      varchar(500),
    created_at  timestamp(6) NOT NULL,
    CONSTRAINT ck_booking_status_history_status CHECK (
        (from_status IS NULL OR from_status IN ('PENDING', 'CONFIRMED', 'PAID', 'CANCELLED'))
        AND to_status IN ('PENDING', 'CONFIRMED', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_booking_status_history_actor CHECK (actor IN ('CUSTOMER', 'PROVIDER', 'ADMIN', 'SYSTEM'))
);
CREATE INDEX idx_booking_status_history_booking ON booking_status_history (booking_id);
CREATE INDEX idx_booking_status_history_actor ON booking_status_history (actor_id);
ALTER TABLE booking_status_history ENABLE ROW LEVEL SECURITY;

