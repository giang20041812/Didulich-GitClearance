--changeset viettrek:v2-004-payment
--comment: Cổng thanh toán, giao dịch và hoàn tiền. Mỗi đơn tối đa một giao dịch SUCCESS và một yêu cầu hoàn tiền PENDING (index duy nhất một phần).
CREATE TABLE payment_gateway (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      varchar(32)  NOT NULL,
    name      varchar(128) NOT NULL,
    is_active boolean      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_payment_gateway_code UNIQUE (code)
);
ALTER TABLE payment_gateway ENABLE ROW LEVEL SECURITY;

CREATE TABLE payment_transaction (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      bigint         NOT NULL REFERENCES booking (id),
    gateway_id      bigint         NOT NULL REFERENCES payment_gateway (id),
    external_txn_id varchar(128),
    amount          numeric(14, 2) NOT NULL,
    currency        char(3)        NOT NULL DEFAULT 'VND',
    status          varchar(16)    NOT NULL DEFAULT 'INITIATED',
    initiated_at    timestamp(6)   NOT NULL,
    paid_at         timestamp(6),
    raw_callback    jsonb,
    CONSTRAINT ck_payment_transaction_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_transaction_status CHECK (status IN ('INITIATED', 'SUCCESS', 'FAILED', 'CANCELLED', 'EXPIRED'))
);
CREATE UNIQUE INDEX uq_payment_transaction_success ON payment_transaction (booking_id) WHERE status = 'SUCCESS';
CREATE INDEX idx_payment_transaction_booking ON payment_transaction (booking_id);
CREATE INDEX idx_payment_transaction_gateway ON payment_transaction (gateway_id);
CREATE INDEX idx_payment_transaction_status_paid ON payment_transaction (status, paid_at);
ALTER TABLE payment_transaction ENABLE ROW LEVEL SECURITY;

CREATE TABLE refund (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id             bigint         NOT NULL REFERENCES booking (id),
    payment_transaction_id bigint         NOT NULL REFERENCES payment_transaction (id),
    refund_type            varchar(16)    NOT NULL DEFAULT 'FULL_REFUND',
    amount                 numeric(14, 2) NOT NULL,
    reason                 varchar(500)   NOT NULL,
    status                 varchar(16)    NOT NULL DEFAULT 'PENDING',
    requested_at           timestamp(6)   NOT NULL,
    processed_at           timestamp(6),
    processed_by           bigint REFERENCES account (id) ON DELETE SET NULL,
    CONSTRAINT ck_refund_type CHECK (refund_type IN ('FULL_REFUND', 'NO_REFUND')),
    CONSTRAINT ck_refund_amount CHECK (amount >= 0),
    CONSTRAINT ck_refund_status CHECK (status IN ('PENDING', 'PROCESSED', 'REJECTED'))
);
CREATE UNIQUE INDEX uq_refund_pending ON refund (booking_id) WHERE status = 'PENDING';
CREATE INDEX idx_refund_booking ON refund (booking_id);
CREATE INDEX idx_refund_payment_transaction ON refund (payment_transaction_id);
CREATE INDEX idx_refund_processed_by ON refund (processed_by);
CREATE INDEX idx_refund_status_processed ON refund (status, processed_at);
ALTER TABLE refund ENABLE ROW LEVEL SECURITY;

