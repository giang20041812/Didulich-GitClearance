--changeset viettrek:v2-004-review
--comment: Đánh giá của khách cho một đơn đã thanh toán (mỗi đơn tối đa một đánh giá) và ảnh đính kèm theo thứ tự.
CREATE TABLE review (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id          bigint       NOT NULL REFERENCES place (id),
    booking_id        bigint       NOT NULL REFERENCES booking (id),
    rating            smallint     NOT NULL,
    content           text,
    status            varchar(16)  NOT NULL DEFAULT 'VISIBLE',
    editable_until    timestamp(6) NOT NULL,
    created_at        timestamp(6) NOT NULL,
    updated_at        timestamp(6) NOT NULL,
    provider_reply    text,
    provider_reply_at timestamp(6),
    provider_reply_by bigint REFERENCES account (id) ON DELETE SET NULL,
    moderated_by      bigint REFERENCES account (id) ON DELETE SET NULL,
    moderated_at      timestamp(6),
    moderation_reason varchar(500),
    CONSTRAINT uq_review_booking UNIQUE (booking_id),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_review_status CHECK (status IN ('VISIBLE', 'HIDDEN', 'REMOVED'))
);
CREATE INDEX idx_review_place ON review (place_id, status);
CREATE INDEX idx_review_status_created ON review (status, created_at);
CREATE INDEX idx_review_provider_reply_by ON review (provider_reply_by);
CREATE INDEX idx_review_moderated_by ON review (moderated_by);
ALTER TABLE review ENABLE ROW LEVEL SECURITY;

